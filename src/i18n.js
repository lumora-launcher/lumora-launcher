  function getGreeting(lang, name) {
    const d = dict(lang);
    const h = new Date().getHours();
    const idx = h < 6 ? 0 : h < 12 ? 1 : h < 18 ? 2 : 3;
    const part = d.greetings[idx];
    return name ? `${part}, ${name}` : part || d.greeting_anon;
  }

